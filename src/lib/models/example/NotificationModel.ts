/**
 * Notification Model - Example Neogma OGM Model
 *
 * This is a complete example showing how to create type-safe OGM models.
 * Use this as a reference when creating new models for features.
 */

import { ModelFactory } from "neogma";
import type { Session } from "neo4j-driver";
import type { ModelRelatedNodesI } from "neogma";
import {
  now,
  withTimestamps,
  touchTimestamp,
  ErrorCodes,
  ModelError,
} from "~/lib/models";
import type { TimestampProperties } from "~/lib/models";

/**
 * Notification Properties Interface
 *
 * Define all properties that can be stored on the Notification node
 */
export interface NotificationProperties extends TimestampProperties {
  id?: string; // Auto-generated by Neo4j
  userId: string; // Reference to User who owns this notification
  type: "info" | "success" | "warning" | "error";
  title: string;
  message: string;
  read: boolean;
  actionUrl?: string; // Optional URL for action button
  actionText?: string; // Optional text for action button
  metadata?: string; // JSON string for additional data
  [key: string]: string | number | boolean | undefined;
}

/**
 * Notification Relationships Interface
 *
 * Define relationships to other models (currently none for simplicity)
 */
export type NotificationRelationships = {};

/**
 * Notification Static Methods Interface
 *
 * Define custom static methods on the model class
 */
export interface NotificationStatics {
  /**
   * Find all notifications for a user
   */
  findByUserId(
    userId: string,
    options?: {
      session?: Session;
      unreadOnly?: boolean;
      limit?: number;
    },
  ): Promise<NotificationInstance[]>;

  /**
   * Mark all notifications as read for a user
   */
  markAllAsReadForUser(userId: string, session?: Session): Promise<number>;

  /**
   * Delete old read notifications
   */
  deleteOldReadNotifications(
    daysOld: number,
    session?: Session,
  ): Promise<number>;

  /**
   * Get unread count for a user
   */
  getUnreadCount(userId: string, session?: Session): Promise<number>;
}

/**
 * Notification Instance Methods Interface
 *
 * Define methods available on model instances
 */
export interface NotificationMethods {
  /**
   * Mark this notification as read
   */
  markAsRead(session?: Session): Promise<void>;

  /**
   * Mark this notification as unread
   */
  markAsUnread(session?: Session): Promise<void>;

  /**
   * Delete this notification
   */
  delete(session?: Session): Promise<void>;

  /**
   * Update notification content
   */
  updateContent(
    data: {
      title?: string;
      message?: string;
      actionUrl?: string;
      actionText?: string;
    },
    session?: Session,
  ): Promise<void>;
}

/**
 * Create the Notification Model
 *
 * Use lazy initialization to ensure neogma is ready
 */
let NotificationModel: ReturnType<typeof createNotificationModel>;

function createNotificationModel() {
  // Get neogma instance from global state
  const neogma = global.__neo4jDriverState?.neogmaInstance;

  if (!neogma) {
    throw new Error(
      "Neogma instance not initialized. Ensure getDriver() has been called.",
    );
  }

  const model = ModelFactory<
    NotificationProperties,
    NotificationRelationships,
    NotificationStatics,
    NotificationMethods
  >(
    {
      label: "Notification",
      schema: {
        userId: {
          type: "string",
          required: true,
        },
        type: {
          type: "string",
          required: true,
        },
        title: {
          type: "string",
          required: true,
        },
        message: {
          type: "string",
          required: true,
        },
        read: {
          type: "boolean",
          required: true,
          default: false,
        },
        actionUrl: {
          type: "string",
          required: false,
        },
        actionText: {
          type: "string",
          required: false,
        },
        metadata: {
          type: "string",
          required: false,
        },
        createdAt: {
          type: "string",
          required: false,
        },
        updatedAt: {
          type: "string",
          required: false,
        },
      },
      relationships: {
        // Example relationship definition (commented out):
        // belongsToUser: {
        //   model: UserModel,
        //   direction: "out" as const,
        //   name: "BELONGS_TO_USER",
        //   properties: {},
        // },
      },
    },
    neogma,
  );

  // ==================== STATIC METHODS ====================

  model.findByUserId = async (userId, options = {}) => {
    const { session, unreadOnly = false, limit } = options;

    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    const where: any = { userId };
    if (unreadOnly) {
      where.read = false;
    }

    const queryOptions: any = { where };
    if (limit) {
      queryOptions.limit = limit;
    }

    const notifications = await model.findMany(queryOptions, session);
    return notifications;
  };

  model.markAllAsReadForUser = async (userId, session) => {
    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    const result = await session.run(
      `
      MATCH (n:Notification {userId: $userId, read: false})
      SET n.read = true, n.updatedAt = $updatedAt
      RETURN count(n) as count
      `,
      { userId, updatedAt: now() },
    );

    return result.records[0]?.get("count")?.toNumber() || 0;
  };

  model.deleteOldReadNotifications = async (daysOld, session) => {
    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    const cutoffDate = new Date();
    cutoffDate.setDate(cutoffDate.getDate() - daysOld);
    const cutoffIso = cutoffDate.toISOString();

    const result = await session.run(
      `
      MATCH (n:Notification {read: true})
      WHERE n.createdAt < $cutoffDate
      DELETE n
      RETURN count(n) as count
      `,
      { cutoffDate: cutoffIso },
    );

    return result.records[0]?.get("count")?.toNumber() || 0;
  };

  model.getUnreadCount = async (userId, session) => {
    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    const result = await session.run(
      `
      MATCH (n:Notification {userId: $userId, read: false})
      RETURN count(n) as count
      `,
      { userId },
    );

    return result.records[0]?.get("count")?.toNumber() || 0;
  };

  // ==================== INSTANCE METHODS ====================

  model.prototype.markAsRead = async function (session) {
    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    await this.update(
      {
        read: true,
        updatedAt: now(),
      },
      session,
    );
  };

  model.prototype.markAsUnread = async function (session) {
    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    await this.update(
      {
        read: false,
        updatedAt: now(),
      },
      session,
    );
  };

  model.prototype.delete = async function (session) {
    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    await this.delete(session);
  };

  model.prototype.updateContent = async function (data, session) {
    if (!session) {
      throw new ModelError("Session is required", ErrorCodes.SESSION_REQUIRED);
    }

    const updates = touchTimestamp(data);
    await this.update(updates, session);
  };

  return model;
}

/**
 * Get or create the Notification Model instance
 *
 * This lazy initialization ensures neogma is ready before creating the model
 */
export function getNotificationModel() {
  if (!NotificationModel) {
    NotificationModel = createNotificationModel();
  }
  return NotificationModel;
}

/**
 * Type exports for usage in other files
 */
export type NotificationInstance = InstanceType<typeof NotificationModel>;
export type NotificationModelType = typeof NotificationModel;

/**
 * Helper function to create a notification
 *
 * This is a convenience wrapper that adds timestamps automatically
 */
export async function createNotification(
  data: Omit<NotificationProperties, "id" | "createdAt" | "updatedAt" | "read">,
  session: Session,
): Promise<NotificationInstance> {
  const model = getNotificationModel();

  const notificationData = withTimestamps({
    ...data,
    read: false,
  });

  return await model.createOne(notificationData, { session });
}
